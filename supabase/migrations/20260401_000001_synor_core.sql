create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.teachers_whitelist (
  email text primary key,
  is_super boolean not null default false,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null,
  role text not null check (role in ('student', 'teacher')),
  is_super boolean not null default false,
  group_id bigint references public.groups(id) on delete set null,
  university text,
  program text,
  course_year text,
  bio text,
  gpa double precision,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  subject text not null,
  teacher_id uuid not null references public.users(id) on delete cascade,
  group_id bigint not null references public.groups(id) on delete cascade,
  start_time timestamptz not null,
  end_time timestamptz not null,
  room text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint lessons_time_range_check check (end_time > start_time)
);

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  title text not null,
  file_url text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists users_group_id_idx on public.users (group_id);
create index if not exists users_role_idx on public.users (role);
create index if not exists lessons_teacher_id_idx on public.lessons (teacher_id);
create index if not exists lessons_group_id_idx on public.lessons (group_id);
create index if not exists lessons_start_time_idx on public.lessons (start_time);
create index if not exists materials_lesson_id_idx on public.materials (lesson_id);
create index if not exists materials_created_at_idx on public.materials (created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

