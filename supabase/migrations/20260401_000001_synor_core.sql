create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role
  from public.users
  where id = auth.uid()
$$;

create or replace function public.current_user_is_super()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(is_super, false)
  from public.users
  where id = auth.uid()
$$;

create or replace function public.current_user_group_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select group_id
  from public.users
  where id = auth.uid()
$$;

create or replace function public.handle_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_role text;
  effective_role text;
  requested_group_name text;
  resolved_group_id bigint;
  whitelist_super boolean := false;
  resolved_name text;
begin
  requested_role := lower(coalesce(new.raw_user_meta_data ->> 'role', 'student'));
  effective_role := case
    when requested_role = 'teacher' then 'teacher'
    else 'student'
  end;

  requested_group_name := nullif(trim(coalesce(new.raw_user_meta_data ->> 'group', '')), '');
  if requested_group_name is not null then
    select g.id
      into resolved_group_id
      from public.groups g
     where lower(g.name) = lower(requested_group_name)
     limit 1;
  end if;

  select coalesce(tw.is_super, false)
    into whitelist_super
    from public.teachers_whitelist tw
   where lower(tw.email) = lower(new.email)
   limit 1;

  resolved_name := nullif(trim(coalesce(new.raw_user_meta_data ->> 'name', '')), '');
  if resolved_name is null then
    resolved_name := split_part(coalesce(new.email, ''), '@', 1);
  end if;

  insert into public.users (
    id,
    email,
    name,
    role,
    is_super,
    group_id,
    university,
    program,
    course_year
  )
  values (
    new.id,
    coalesce(new.email, ''),
    resolved_name,
    effective_role,
    whitelist_super,
    case when effective_role = 'student' then resolved_group_id else null end,
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'university', '')), ''),
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'faculty', '')), ''),
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'course_year', '')), '')
  )
  on conflict (id) do update
    set email = excluded.email,
        name = excluded.name,
        role = excluded.role,
        is_super = public.users.is_super or excluded.is_super,
        group_id = coalesce(excluded.group_id, public.users.group_id),
        university = excluded.university,
        program = excluded.program,
        course_year = excluded.course_year;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_auth_user();

